use anyhow::{Result, anyhow};
use std::{
    fs::{create_dir_all, read_to_string},
    path::PathBuf,
};
use tracing::{debug, info, instrument};

use crate::parsers;

#[derive(Debug)]
enum PublicKind {
    Typedef,
    Struct,
    Union,
    Enum,
    Extern,
    Function,
}

struct PublicDefinition {
    header: String,
    source: String,
}

struct RecordingLines<'source, I> {
    lines: I,
    source: &'source mut String,
}

impl<'line, 'source, I> Iterator for RecordingLines<'source, I>
where
    I: Iterator<Item = (usize, &'line str)>,
{
    type Item = (usize, &'line str);

    fn next(&mut self) -> Option<Self::Item> {
        let (line_number, line) = self.lines.next()?;
        self.source.push_str(line);
        self.source.push('\n');
        Some((line_number, line))
    }
}

fn classify(line: &str) -> PublicKind {
    match line.split_whitespace().next() {
        Some("typedef") => PublicKind::Typedef,
        Some("struct") => PublicKind::Struct,
        Some("union") => PublicKind::Union,
        Some("enum") => PublicKind::Enum,
        Some("extern") => PublicKind::Extern,
        _ => PublicKind::Function,
    }
}

fn annotation_marker(line: &str) -> Option<&str> {
    let line = line.trim();
    if line == "@public" {
        return Some("@public");
    }

    line.strip_prefix("//").map(str::trim).filter(|line| {
        matches!(
            *line,
            "@public" | "@directives" | "@implementation" | "@all" | "@end"
        )
    })
}

pub struct Generator {
    files: Vec<(PathBuf, PathBuf)>,
    dir: PathBuf,
}

impl Generator {
    #[instrument(
        name = "generator.new",
        skip(files),
        fields(file_count = files.len(), output_dir = %dir.display())
    )]
    pub fn new(files: Vec<(PathBuf, PathBuf)>, dir: PathBuf) -> Self {
        Self { files, dir }
    }

    #[instrument(
        name = "generator.parse_public",
        skip(self, lines),
        fields(marker_line = marker_line + 1)
    )]
    fn parse_public<'a>(
        &self,
        lines: &mut impl Iterator<Item = (usize, &'a str)>,
        marker_line: usize,
    ) -> Result<PublicDefinition> {
        let (_, first_line) = lines.next().ok_or_else(|| {
            anyhow!(
                "There's no definition under @public at line {}",
                marker_line + 1
            )
        })?;

        let mut source = String::new();
        source.push_str(first_line);
        source.push('\n');

        let mut recording_lines = RecordingLines {
            lines,
            source: &mut source,
        };
        let kind = classify(first_line);
        debug!(?kind, "classified public definition");

        let header = match kind {
            PublicKind::Typedef => parsers::typedef_parser(first_line, &mut recording_lines),
            PublicKind::Struct => parsers::struct_parser(first_line, &mut recording_lines),
            PublicKind::Union => parsers::union_parser(first_line, &mut recording_lines),
            PublicKind::Enum => parsers::enum_parser(first_line, &mut recording_lines),
            PublicKind::Extern => parsers::extern_parser(first_line, &mut recording_lines),
            PublicKind::Function => parsers::function_parser(first_line, &mut recording_lines),
        }?;

        debug!(
            header_bytes = header.len(),
            source_bytes = source.len(),
            "parsed public definition"
        );
        Ok(PublicDefinition { header, source })
    }

    fn parse_annotation_block<'a>(
        &self,
        lines: &mut impl Iterator<Item = (usize, &'a str)>,
        marker_line: usize,
        block_name: &str,
    ) -> Result<Vec<String>> {
        let mut contents = Vec::new();

        while let Some((line_number, line)) = lines.next() {
            let marker = annotation_marker(line);
            match marker {
                Some("@end") => return Ok(contents),
                Some(nested_marker) => {
                    return Err(anyhow!(
                        "Nested {} marker at line {}: it may not appear inside a @{} block",
                        nested_marker,
                        line_number + 1,
                        block_name
                    ));
                }
                None => contents.push(line.trim().to_string()),
            }
        }

        Err(anyhow!(
            "Unterminated @{} block starting at line {}: missing // @end",
            block_name,
            marker_line + 1
        ))
    }

    fn process_source(&self, file: &str) -> Result<(String, String)> {
        let mut lines = file.lines().enumerate();
        let mut generated_source = String::new();
        let mut header_source = String::from("// THIS FILE WAS GENERATED BY HEADERLESS\n\n");

        while let Some((line_number, line)) = lines.next() {
            match annotation_marker(line) {
                Some("@public") => {
                    let definition = self.parse_public(&mut lines, line_number)?;
                    header_source.push_str(format!("{}\n", &definition.header).as_str());
                    generated_source.push_str(&definition.source);
                }
                Some("@directives") => {
                    let directives =
                        self.parse_annotation_block(&mut lines, line_number, "directives")?;
                    for line in directives {
                        header_source.push_str(&line);
                        header_source.push('\n');
                    }
                }
                Some("@implementation") => {
                    let implementation =
                        self.parse_annotation_block(&mut lines, line_number, "implementation")?;
                    for line in implementation {
                        generated_source.push_str(&line);
                        generated_source.push('\n');
                    }
                }
                Some("@all") => {
                    let contents = self.parse_annotation_block(&mut lines, line_number, "all")?;
                    for line in contents {
                        header_source.push_str(&line);
                        header_source.push('\n');
                        generated_source.push_str(&line);
                        generated_source.push('\n');
                    }
                }
                Some("@end") => {
                    return Err(anyhow!(
                        "Unexpected // @end at line {}: it does not close an @directives block",
                        line_number + 1
                    ));
                }
                Some(_) | None => {
                    generated_source.push_str(line.trim());
                    generated_source.push('\n');
                }
            }
        }

        Ok((generated_source, header_source))
    }

    #[instrument(
        name = "generator.generate",
        skip(self),
        fields(
            file_count = self.files.len(),
            output_dir = %self.dir.display()
        )
    )]
    pub fn generate(&mut self) -> Result<()> {
        create_dir_all(&self.dir)?;
        info!("starting source generation");

        for (file, relative) in &self.files {
            let file_span = tracing::info_span!("generator.file", input = %file.display());
            let _file_span = file_span.enter();

            let source_path = self.dir.join(relative);
            let header_path = source_path.with_extension("h");
            let file = read_to_string(file)?;
            debug!(source_bytes = file.len(), "read source file");
            let (generated_source, header_source) = self.process_source(&file)?;

            if let Some(parent) = source_path.parent() {
                create_dir_all(parent)?;
            }

            std::fs::write(source_path, &generated_source)?;
            std::fs::write(header_path, &header_source)?;
            info!(
                generated_source_bytes = generated_source.len(),
                generated_header_bytes = header_source.len(),
                "wrote generated files"
            );
        }

        info!("finished source generation");
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::Generator;
    use std::path::PathBuf;
    use std::process::Command;
    use std::time::{SystemTime, UNIX_EPOCH};

    fn generator() -> Generator {
        Generator::new(Vec::<(PathBuf, PathBuf)>::new(), PathBuf::from("generated"))
    }

    #[test]
    fn directives_are_header_only() {
        let source = "// @directives\n#include <stddef.h>\n#define HEADERLESS_FEATURE_X\n// @end\n";
        let (generated_source, header) = generator().process_source(source).unwrap();

        assert!(!generated_source.contains("#include <stddef.h>"));
        assert!(!generated_source.contains("#define HEADERLESS_FEATURE_X"));
        assert!(!generated_source.contains("@directives"));
        assert!(!generated_source.contains("@end"));
        assert!(header.contains("#include <stddef.h>\n"));
        assert!(header.contains("#define HEADERLESS_FEATURE_X\n"));
    }

    #[test]
    fn implementation_is_source_only_and_preserves_order() {
        let source = "\
// @implementation
#include <stdio.h>
#define FIRST 1
// @end
// @implementation
#define SECOND 2
// @end
";
        let (generated_source, header) = generator().process_source(source).unwrap();

        assert!(
            generated_source.find("#include <stdio.h>").unwrap()
                < generated_source.find("#define FIRST").unwrap()
        );
        assert!(
            generated_source.find("#define FIRST").unwrap()
                < generated_source.find("#define SECOND").unwrap()
        );
        assert!(!header.contains("#include <stdio.h>"));
        assert!(!header.contains("#define FIRST"));
        assert!(!header.contains("#define SECOND"));
    }

    #[test]
    fn all_is_emitted_to_source_and_header_in_order() {
        let source = "\
// @all
#include <stdint.h>
#define SHARED 1
// @end
";
        let (generated_source, header) = generator().process_source(source).unwrap();

        assert!(generated_source.contains("#include <stdint.h>\n"));
        assert!(header.contains("#include <stdint.h>\n"));
        assert!(
            generated_source.find("#include").unwrap() < generated_source.find("#define").unwrap()
        );
        assert!(header.find("#include").unwrap() < header.find("#define").unwrap());
    }

    #[test]
    fn processes_multiple_directive_blocks_in_order() {
        let source = "\
// @directives
#define FIRST
// @end
// @directives
#define SECOND
// @end
";
        let (generated_source, header) = generator().process_source(source).unwrap();

        assert!(!generated_source.contains("#define FIRST"));
        assert!(!generated_source.contains("#define SECOND"));
        assert!(header.find("#define FIRST").unwrap() < header.find("#define SECOND").unwrap());
    }

    #[test]
    fn accepts_empty_directive_block() {
        let source = "// @directives\n// @end\n";
        let (generated_source, header) = generator().process_source(source).unwrap();

        assert!(!generated_source.contains("@directives"));
        assert!(!generated_source.contains("@end"));
        assert_eq!(header.matches("#").count(), 0);
    }

    #[test]
    fn rejects_unterminated_directive_block() {
        let error = generator()
            .process_source("// @directives\n#define SOMETHING\n")
            .unwrap_err();
        let message = error.to_string();

        assert!(message.contains("Unterminated @directives block"));
        assert!(message.contains("line 1"));
        assert!(message.contains("@end"));
    }

    #[test]
    fn rejects_stray_end_marker() {
        let error = generator().process_source("// @end\n").unwrap_err();

        assert!(error.to_string().contains("Unexpected // @end"));
    }

    #[test]
    fn rejects_nested_directive_blocks() {
        let error = generator()
            .process_source("// @directives\n// @directives\n#define SOMETHING\n// @end\n")
            .unwrap_err();

        assert!(error.to_string().contains("Nested @directives marker"));
        assert!(error.to_string().contains("line 2"));
    }

    #[test]
    fn directive_blocks_do_not_interfere_with_public() {
        let source = "\
// @directives
#define FEATURE
// @end
// @public
int public_value(void);
";
        let (generated_source, header) = generator().process_source(source).unwrap();

        assert!(!generated_source.contains("#define FEATURE"));
        assert!(generated_source.contains("int public_value(void);"));
        assert!(header.contains("#define FEATURE\n"));
        assert!(header.contains("int public_value(void);"));
    }

    #[test]
    fn implementation_and_directive_block_malformed_errors() {
        let implementation_error = generator()
            .process_source("// @implementation\n#include <stdio.h>\n")
            .unwrap_err();
        assert!(
            implementation_error
                .to_string()
                .contains("Unterminated @implementation")
        );

        let all_error = generator()
            .process_source("// @all\n#define SHARED\n")
            .unwrap_err();
        assert!(all_error.to_string().contains("Unterminated @all"));
    }

    #[test]
    fn generated_source_with_implementation_dependency_compiles() {
        let source = "\
// @directives
#include <stddef.h>
// @end
// @implementation
#include <stdio.h>
// @end
// @public
int compiled_test(void) {
    puts(\"ok\");
    return 0;
}
";
        let (generated_source, header) = generator().process_source(source).unwrap();

        assert!(!generated_source.contains("#include <stddef.h>"));
        assert!(generated_source.contains("#include <stdio.h>"));
        assert!(header.contains("#include <stddef.h>"));

        let id = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let dir = std::env::temp_dir().join(format!("headerless_compile_{id}"));
        std::fs::create_dir_all(&dir).unwrap();
        let source_path = dir.join("compiled_test.c");
        std::fs::write(&source_path, generated_source).unwrap();

        let output = Command::new("cc")
            .args(["-c", source_path.to_str().unwrap(), "-o"])
            .arg(dir.join("compiled_test.o"))
            .output()
            .unwrap();
        let _ = std::fs::remove_dir_all(&dir);

        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
}
